package com.example.domain.engine

/**
 * High-performance in-memory Trie (Prefix Tree) for <1ms word validation, skeleton pattern
 * matching (e.g., "P_ANET", "C_OSS"), prefix pruning, and anagram solving.
 */
class WordTrieEngine {

  private class TrieNode {
    val children = IntArray(ALPHABET_SIZE) { -1 }
    var isTerminal: Boolean = false
  }

  private val nodes = ArrayList<TrieNode>(20_480).apply { add(TrieNode()) }
  var wordCount: Int = 0
    private set

  init {
    loadBuiltInLexicon()
  }

  fun insert(word: String) {
    if (word.length < 2) return
    var currentIndex = 0
    for (i in word.indices) {
      val ch = word[i].uppercaseChar()
      if (ch !in 'A'..'Z') return
      val charIdx = ch - 'A'
      var nextNodeIndex = nodes[currentIndex].children[charIdx]
      if (nextNodeIndex == -1) {
        nextNodeIndex = nodes.size
        nodes.add(TrieNode())
        nodes[currentIndex].children[charIdx] = nextNodeIndex
      }
      currentIndex = nextNodeIndex
    }
    if (!nodes[currentIndex].isTerminal) {
      nodes[currentIndex].isTerminal = true
      wordCount++
    }
  }

  fun isValidWord(word: String): Boolean {
    if (word.length < 2) return false
    var currentIndex = 0
    for (i in word.indices) {
      val ch = word[i].uppercaseChar()
      if (ch !in 'A'..'Z') return false
      val nextIndex = nodes[currentIndex].children[ch - 'A']
      if (nextIndex == -1) return false
      currentIndex = nextIndex
    }
    return nodes[currentIndex].isTerminal
  }

  fun hasPrefix(prefix: String): Boolean {
    if (prefix.isEmpty()) return true
    var currentIndex = 0
    for (i in prefix.indices) {
      val ch = prefix[i].uppercaseChar()
      if (ch !in 'A'..'Z') return false
      val nextIndex = nodes[currentIndex].children[ch - 'A']
      if (nextIndex == -1) return false
      currentIndex = nextIndex
    }
    return true
  }

  /**
   * Returns true in <0.5ms if at least one valid dictionary word matches [pattern],
   * where '_' or '?' represents any unfilled blank slot on the crossword skeleton.
   */
  fun hasPatternMatch(pattern: String): Boolean {
    if (pattern.length < 2) return false
    fun dfs(nodeIdx: Int, charPos: Int): Boolean {
      if (charPos == pattern.length) {
        return nodes[nodeIdx].isTerminal
      }
      val ch = pattern[charPos].uppercaseChar()
      val node = nodes[nodeIdx]
      if (ch == '_' || ch == '?') {
        for (c in 0 until ALPHABET_SIZE) {
          val child = node.children[c]
          if (child != -1 && dfs(child, charPos + 1)) {
            return true
          }
        }
        return false
      } else {
        if (ch !in 'A'..'Z') return false
        val child = node.children[ch - 'A']
        return child != -1 && dfs(child, charPos + 1)
      }
    }
    return dfs(0, 0)
  }

  /**
   * Finds all dictionary words matching a crossword skeleton [pattern] (e.g., "P_ANET" -> ["PLANET"]).
   */
  fun matchesPattern(pattern: String, maxResults: Int = 25): List<String> {
    if (pattern.length < 2) return emptyList()
    val results = ArrayList<String>()
    val sb = StringBuilder(pattern.length)

    fun dfs(nodeIdx: Int, charPos: Int) {
      if (results.size >= maxResults) return
      if (charPos == pattern.length) {
        if (nodes[nodeIdx].isTerminal) {
          results.add(sb.toString())
        }
        return
      }
      val ch = pattern[charPos].uppercaseChar()
      val node = nodes[nodeIdx]
      if (ch == '_' || ch == '?') {
        for (c in 0 until ALPHABET_SIZE) {
          val child = node.children[c]
          if (child != -1) {
            sb.append(('A'.code + c).toChar())
            dfs(child, charPos + 1)
            sb.deleteCharAt(sb.length - 1)
          }
        }
      } else if (ch in 'A'..'Z') {
        val child = node.children[ch - 'A']
        if (child != -1) {
          sb.append(ch)
          dfs(child, charPos + 1)
          sb.deleteCharAt(sb.length - 1)
        }
      }
    }

    dfs(0, 0)
    return results
  }

  /**
   * Finds all valid words that can be formed from [letters] in <2ms using Trie-guided DFS.
   */
  fun findAnagrams(letters: List<Char>, minLength: Int = 2, maxResults: Int = 60): List<String> {
    val counts = IntArray(ALPHABET_SIZE)
    for (c in letters) {
      val up = c.uppercaseChar()
      if (up in 'A'..'Z') counts[up - 'A']++
    }
    val results = ArrayList<String>()
    val sb = StringBuilder()

    fun dfs(nodeIndex: Int) {
      if (results.size >= maxResults) return
      val node = nodes[nodeIndex]
      if (node.isTerminal && sb.length >= minLength) {
        results.add(sb.toString())
      }
      for (i in 0 until ALPHABET_SIZE) {
        if (counts[i] > 0) {
          val childIdx = node.children[i]
          if (childIdx != -1) {
            counts[i]--
            sb.append(('A'.code + i).toChar())
            dfs(childIdx)
            sb.deleteCharAt(sb.length - 1)
            counts[i]++
          }
        }
      }
    }

    dfs(0)
    return results.sortedWith(compareByDescending<String> { it.length }.thenBy { it })
  }

  private fun loadBuiltInLexicon() {
    for (chunk in BUILT_IN_LEXICON_CHUNKS) {
      val words = chunk.split(' ')
      for (w in words) {
        if (w.isNotBlank()) insert(w)
      }
    }
  }

